#!/usr/bin/env node
/**
 * Regenerates the typed `--vaadin-*` custom-property declarations, one object per owning
 * component package, from the installed `@vaadin/*` npm packages:
 *
 *   - names are everything a component documents (`*.d.ts` property tables) plus everything its
 *     CSS and JS declare or read, so internal theme plumbing stays out but public properties that
 *     are only mentioned in styles still show up;
 *   - the owner is the longest `--vaadin-<package>-` prefix; the shared field family
 *     (`--vaadin-input-field-*`, `--vaadin-field-*`) goes to `field-base`, a name without a prefix
 *     of its own goes to its single reader, and design tokens read by several components stay in
 *     the root `VaadinSharedCustomProperties`;
 *   - the Kotlin type is inferred from the CSS property the name feeds, then from the name suffix,
 *     then from its default value.
 *
 * Usage:
 *   node scripts/generate-custom-properties.mjs            # rewrite the files
 *   node scripts/generate-custom-properties.mjs --check     # exit 1 on drift
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const NPM_ROOT = path.join(ROOT, 'build/js/node_modules/@vaadin')
const SRC_ROOT = path.join(
  ROOT,
  'ktjs-vaadin-web-components/src/jsMain/kotlin/io/github/shijianjs/ktjs/vaadin',
)
const PACKAGE_PREFIX = 'io.github.shijianjs.ktjs.vaadin'
const MARKER = '// Generated by scripts/generate-custom-properties.mjs. Do not edit.'
const THEME_PACKAGES = new Set(['aura', 'vaadin-lumo-styles'])
/** Base packages that hold shared plumbing rather than one user-facing component. */
const INFRA_PACKAGES = new Set(['component-base', 'a11y-base'])
/** Properties of components this wrapper does not package (paid or React-only), plus theme
 *  switches: they only exist in the themes, and nothing here can consume them. */
const EXCLUDED_PREFIXES = [
  '--vaadin-charts-',
  '--vaadin-crud-',
  '--vaadin-dashboard-',
  '--vaadin-map',
  '--vaadin-rich-text-editor-',
  '--vaadin-chip-',
  '--vaadin-infinite-scroller-',
  '--vaadin-ai-field-',
  '--vaadin-board',
  '--vaadin-grid-pro',
  '--vaadin-lumo-theme',
  '--vaadin-aura-theme',
]
const check = process.argv.includes('--check')

if (!fs.existsSync(NPM_ROOT)) {
  console.error(`npm packages not installed: ${NPM_ROOT}\nRun the JS build once (./gradlew kotlinNpmInstall).`)
  process.exit(1)
}

const packages = fs
  .readdirSync(NPM_ROOT, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name.replace(/^vaadin-/, ''))

/** name -> packages that document it */
const documentedBy = new Map()
/** name -> CSS properties it is fed into */
const usedBy = new Map()
/** name -> { package, value } of the declaration the theme does not shadow */
const declaredIn = new Map()
/** name -> every package that declares or reads it */
const mentionedBy = new Map()
/** names the themes declare: design tokens, regardless of which component reads them */
const themeDeclared = new Set()

function mention(name, pkg) {
  const mentioned = mentionedBy.get(name) ?? new Set()
  mentioned.add(pkg)
  mentionedBy.set(name, mentioned)
}

function walk(dir, pkg) {
  const theme = THEME_PACKAGES.has(pkg)
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === 'dist') continue
      walk(file, pkg)
      continue
    }
    const isDoc = entry.name.endsWith('.d.ts')
    if (!isDoc && !/\.(css|js)$/.test(entry.name)) continue
    const text = fs.readFileSync(file, 'utf8')
    if (isDoc) {
      for (const m of text.matchAll(/`(--vaadin-[a-zA-Z0-9-]+)`/g)) {
        const owners = documentedBy.get(m[1]) ?? new Set()
        owners.add(pkg)
        documentedBy.set(m[1], owners)
      }
      continue
    }
    for (const m of text.matchAll(/([\w-]+)\s*:\s*[^;{}]*?var\((--vaadin-[a-zA-Z0-9-]+)/g)) {
      const props = usedBy.get(m[2]) ?? new Set()
      props.add(m[1])
      usedBy.set(m[2], props)
      if (!theme) mention(m[2], pkg)
    }
    for (const m of text.matchAll(/\[?['"]?(--vaadin-[a-zA-Z0-9-]+)['"]?\]?\s*:\s*([^;{}]+)/g)) {
      const known = declaredIn.get(m[1])
      if (!known) {
        declaredIn.set(m[1], { package: pkg, value: m[2].trim() })
      } else if (THEME_PACKAGES.has(known.package) && !theme) {
        declaredIn.set(m[1], { package: pkg, value: m[2].trim() })
      }
      if (!theme) mention(m[1], pkg)
      if (theme) themeDeclared.add(m[1])
    }
  }
}

for (const entry of fs.readdirSync(NPM_ROOT, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  walk(path.join(NPM_ROOT, entry.name), entry.name.replace(/^vaadin-/, ''))
}

function prefixOwner(name) {
  let owner = null
  for (const pkg of packages) {
    const prefix = '--vaadin-' + pkg
    if ((name === prefix || name.startsWith(prefix + '-')) && (!owner || pkg.length > owner.length)) {
      owner = pkg
    }
  }
  return owner
}

function ownerOf(name) {
  const prefixed = prefixOwner(name)
  if (prefixed) return prefixed
  // The field family is shared by every field component and lives in `@vaadin/field-base`.
  if (/^--vaadin-input-field-|^--vaadin-field-/.test(name)) return 'field-base'
  // Infrastructure packages are not components: `--vaadin-gap-s` sits in `component-base`'s CSS
  // but is a design token every component reads.
  const components = (set) => [...(set ?? [])].filter((pkg) => !INFRA_PACKAGES.has(pkg))
  // A component's own documentation is authoritative: `--vaadin-message-*` belongs to
  // `message-list` because that is where it is documented, not because the theme declares a
  // default for it.
  const documented = components(documentedBy.get(name))
  if (documented.length === 1) return documented[0]
  // A name the themes declare without a component prefix is a design token: `--vaadin-gap-s`,
  // `--vaadin-text-color`, `--vaadin-focus-ring-color`, … Every component reads the same one.
  if (themeDeclared.has(name)) return ''
  const declared = declaredIn.get(name)
  if (
    declared &&
    !INFRA_PACKAGES.has(declared.package) &&
    !THEME_PACKAGES.has(declared.package) &&
    packages.includes(declared.package)
  ) {
    return declared.package
  }
  // A name without a prefix of its own belongs to the single component that reads it, e.g.
  // `--vaadin-tab-*` → `tabs`; names several components read stay shared.
  const mentioning = components(mentionedBy.get(name))
  if (mentioning.length === 1) return mentioning[0]
  return ''
}

// --- type inference -------------------------------------------------------------------------

const LENGTH_PROPERTIES = [
  /^padding/, /^margin/, /^gap/, /^row-gap/, /^column-gap/, /^width/, /^height/, /^min-/, /^max-/,
  /^inset/, /^top$/, /^bottom$/, /^left$/, /^right$/, /^inline-size/, /^block-size/, /^font-size/,
  /^border-radius/, /^outline-offset/, /^letter-spacing/, /^word-spacing/, /^tab-size/,
  /^column-width/, /^flex-basis/, /^background-size/, /^mask-size/, /^translate/, /^vertical-align/,
]
const PROPERTY_TYPES = {
  'box-shadow': 'BoxShadow',
  content: 'Content',
  display: 'Display',
  opacity: 'NumberType',
  transition: 'Transition',
  'transition-duration': 'TransitionDuration',
  'transition-timing-function': 'TransitionTimingFunction',
  'font-family': 'FontFamily',
  'line-height': 'LineHeight',
  'font-weight': 'FontWeight',
  'border-style': 'BorderStyle',
  'outline-style': 'OutlineStyle',
  cursor: 'Cursor',
  background: 'Background',
  border: 'Border',
  outline: 'Outline',
  'white-space': 'WhiteSpace',
  'text-overflow': 'TextOverflow',
  'clip-path': 'ClipPath',
  mask: 'Mask',
  scale: 'Scale',
  'stroke-width': 'StrokeWidth',
  'aspect-ratio': 'AspectRatio',
  'text-align': 'TextAlign',
  'animation-duration': 'AnimationDuration',
  'justify-content': 'JustifyContent',
  transform: 'Transform',
}
/** Flags a component reads in JS as `'true'`; they have no CSS counterpart, hence plain `String`. */
const FLAG_NAMES = new Set([
  '--vaadin-app-layout-drawer-overlay',
  '--vaadin-app-layout-touch-optimized',
])
const NAME_TYPES = [
  [/-font-weight$/, 'FontWeight'],
  [/-line-height$/, 'LineHeight'],
  [/-font-family$/, 'FontFamily'],
  [/-color$/, 'Color'],
  [/-background$/, 'Color'],
  [/-surface$/, 'Color'],
  [/-backdrop$/, 'Color'],
  [/-shadow$/, 'BoxShadow'],
  [/-highlight$/, 'Color'],
  [/-required-indicator$/, 'Content'],
  [/-checkmark$/, 'Content'],
  [/-indicator$/, 'Content'],
  [/-timing-function$/, 'TransitionTimingFunction'],
  [/-animation-duration$/, 'AnimationDuration'],
  [/-transition-duration$/, 'TransitionDuration'],
  [/-opacity$/, 'NumberType'],
  [/-border-width$/, 'Length'],
  [/-border-radius$/, 'Length'],
  [/-padding$/, 'Length'],
  [/-gap$/, 'Length'],
  [/-spacing$/, 'Length'],
  [/-indent$/, 'Length'],
  [/-offset$/, 'Length'],
  [/-inset$/, 'Length'],
  [/-size$/, 'Length'],
  [/-height$/, 'Length'],
  [/-width$/, 'Length'],
  [/-radius$/, 'Length'],
  [/-margin$/, 'Length'],
  [/-overlap$/, 'Length'],
  [/-aspect-ratio$/, 'AspectRatio'],
  [/-text-align$/, 'TextAlign'],
]
const LUMO_HINTS = [
  [/-color/, 'Color'],
  [/^--lumo-(contrast|shade|tint|base)/, 'Color'],
  [/box-shadow/, 'BoxShadow'],
  [/line-height/, 'LineHeight'],
  [/font-family/, 'FontFamily'],
  [/icons-/, 'Content'],
  [/space|size|border-radius|font-size/, 'Length'],
]

function fromName(name) {
  for (const [pattern, type] of NAME_TYPES) if (pattern.test(name)) return type
  return null
}

function fromProperties(name) {
  const types = new Set()
  for (const prop of usedBy.get(name) ?? []) {
    if (PROPERTY_TYPES[prop]) {
      types.add(PROPERTY_TYPES[prop])
      continue
    }
    if (LENGTH_PROPERTIES.some((pattern) => pattern.test(prop))) {
      types.add('Length')
      continue
    }
    if (/^color$|-color$|^background|^fill$|^stroke$/.test(prop)) types.add('Color')
  }
  // A colour satisfies `background`, a width satisfies `border`/`outline` and vice versa.
  if (types.has('Color')) types.delete('Background')
  if (types.has('Length')) {
    types.delete('Border')
    types.delete('Outline')
  }
  return types.size === 1 ? [...types][0] : types.size > 1 ? null : undefined
}

function fromValue(value, seen) {
  const v = value.trim()
  if (v.includes('gradient(')) return 'Background'
  if (/^#|^rgb|^hsl|^oklch|^color-mix|^light-dark|^transparent$|^currentColor$/.test(v)) return 'Color'
  if (/^-?[0-9.]+(px|rem|em|%|vh|vw|vmin|vmax|ch|ex|pt|cm|mm|in)$/.test(v)) return 'Length'
  if (/^(calc|min|max|clamp|round|abs|fit-content)\(/.test(v)) return 'Length'
  if (/^\d+(\.\d+)?(ms|s)$/.test(v)) return 'TransitionDuration'
  if (/^0\.\d+$|^[01]$/.test(v)) return 'NumberType'
  if (/^(none|block|inline|inline-block|flex|grid|contents)$/.test(v)) return 'Display'
  if (v.startsWith("'") || v.startsWith('"')) return 'Content'
  const single = /^var\((--[a-z0-9-]+)\)$/.exec(v)
  if (single) {
    const target = single[1]
    if (seen.has(target)) return null
    seen.add(target)
    const declared = declaredIn.get(target)
    if (declared) return fromValue(declared.value, seen)
    for (const [pattern, type] of LUMO_HINTS) if (pattern.test(target)) return type
  }
  for (const [pattern, type] of LUMO_HINTS) if (pattern.test(v)) return type
  return null
}

function typeOf(name) {
  if (FLAG_NAMES.has(name)) return 'String'
  const named = fromName(name)
  if (named) return named
  const byProperties = fromProperties(name)
  if (byProperties) return byProperties
  const declared = declaredIn.get(name)
  return declared ? fromValue(declared.value, new Set([name])) : null
}

// --- rendering ------------------------------------------------------------------------------

function show(name) {
  return '`' + name + '`'
}

function memberOf(name, owner) {
  const prefixes = owner === 'field-base'
    ? ['--vaadin-input-field-', '--vaadin-field-']
    : [owner ? `--vaadin-${owner}-` : '--vaadin-']
  for (const prefix of prefixes) {
    if (name.startsWith(prefix) && name.length > prefix.length) return name.slice(prefix.length)
  }
  return name.replace(/^--vaadin-/, '')
}

function objectName(owner) {
  if (!owner) return 'VaadinSharedCustomProperties'
  return owner.split('-').filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join('') + 'CustomProperties'
}

const names = [...new Set([...documentedBy.keys(), ...mentionedBy.keys(), ...themeDeclared])]
  .filter((name) => !EXCLUDED_PREFIXES.some((prefix) => name.startsWith(prefix)))
  .sort()
const groups = new Map()
const unresolved = []
for (const name of names) {
  const owner = ownerOf(name)
  const type = typeOf(name)
  if (!type) {
    unresolved.push(`${name} (${owner || 'shared'})`)
    continue
  }
  const group = groups.get(owner) ?? new Map()
  group.set(name, type)
  groups.set(owner, group)
}
if (unresolved.length) {
  console.error('Cannot infer a type for:\n  ' + unresolved.join('\n  '))
  process.exit(1)
}

const drift = []
const expected = new Set()
for (const [owner, group] of groups) {
  const npm = owner ? `@vaadin/${owner}` : 'the components that share it'
  const type = objectName(owner)
  const pkg = owner ? `${PACKAGE_PREFIX}.${owner.replace(/-/g, '')}` : PACKAGE_PREFIX
  // Directories follow the package name, not the npm name: `field-base` → `fieldbase`.
  const directory = owner ? path.join(SRC_ROOT, owner.replace(/-/g, '')) : SRC_ROOT
  const file = path.join(directory, `${type}.kt`)

  const members = new Map()
  for (const [name, propertyType] of [...group].sort((a, b) => a[0].localeCompare(b[0]))) {
    const member = memberOf(name, owner).toUpperCase().replaceAll('-', '_')
    if (members.has(member)) {
      throw new Error(`${type}: ${member} declared by both ${name} and ${members.get(member).name}`)
    }
    const feeds = [...(usedBy.get(name) ?? [])].filter((property) => /^[a-z]/.test(property))
    members.set(member, { name, type: propertyType, props: feeds })
  }

  const cssomImports = [...new Set([...members.values()].map((member) => member.type))]
    .filter((type) => type !== 'String')
    .map((type) => `web.cssom.${type}`)
  const imports = ['web.cssom.CustomPropertyName', ...cssomImports].sort()
  // Show the example on a member whose value type has an obvious Lumo counterpart, so the
  // snippet is valid Kotlin rather than a placeholder.
  const examples = {
    Color: 'var(LumoCustomProperties.PRIMARY_TEXT_COLOR)',
    Length: 'var(LumoCustomProperties.SPACE_M)',
  }
  const sample = [...members].find(([, member]) => examples[member.type])
  const exampleLines = sample
    ? [' * ```kotlin', ` * inlineStyle[${type}.${sample[0]}] = ${examples[sample[1].type]}`, ' * ```']
    : []
  const lines = [
    MARKER,
    `package ${pkg}`,
    '',
    ...imports.map((imported) => `import ${imported}`),
    '',
    '/**',
    ` * The custom properties of \`${npm}\` as typed [custom property names][CustomPropertyName].`,
    ' *',
    ' * A custom property is set through the CSSOM custom-property API, which keeps the value tied to',
    ' * the kind of value the component expects:',
    ' *',
    ...exampleLines,
    ' *',
    ' * Members keep their upstream names verbatim; the KDoc lists the CSS properties the component',
    ' * feeds them into. Their defaults come from the Lumo and Aura themes, see `LumoCustomProperties`.',
    ' */',
    `object ${type} {`,
  ]
  for (const [member, { name, type: memberType, props }] of members) {
    const feeds = props.length ? ` Feeds ${props.map(show).join(', ')}.` : ''
    lines.push(`    /** \`${name}\`.${feeds} */`)
    lines.push(`    val ${member}: CustomPropertyName<${memberType}> = CustomPropertyName("${name}")`)
  }
  lines.push('}', '')

  const content = lines.join('\n')
  expected.add(file)
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue
  drift.push(path.relative(ROOT, file))
  if (!check) {
    fs.mkdirSync(directory, { recursive: true })
    fs.writeFileSync(file, content, 'utf8')
  }
}

// Drop declarations this script no longer produces (a component or a property name went away).
for (const entry of fs.readdirSync(SRC_ROOT, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const directory = path.join(SRC_ROOT, entry.name)
  for (const file of fs.readdirSync(directory)) {
    if (!file.endsWith('CustomProperties.kt')) continue
    const full = path.join(directory, file)
    if (expected.has(full)) continue
    if (!fs.readFileSync(full, 'utf8').startsWith(MARKER)) continue
    drift.push(path.relative(ROOT, full))
    if (!check) fs.rmSync(full)
  }
}

if (check) {
  if (drift.length) {
    console.error('Custom property declarations are out of date:\n  ' + drift.join('\n  '))
    process.exit(1)
  }
  console.log('Custom property declarations are up to date')
} else {
  const total = [...groups.values()].reduce((count, group) => count + group.size, 0)
  console.log(`${total} custom properties in ${groups.size} objects`)
}
